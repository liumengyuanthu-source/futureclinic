const PATTERNS = [
  [/^LIVE PROTOTYPE · (S\d+)$/, "可操作原型 · $1"],
  [/^(\d+) evidence items open$/, "$1 項證據待處理"],
  [/^(\d+) open evidence items$/, "$1 項證據待處理"],
  [/^Missing: (.+)$/, "缺失：$1"],
  [/^Grounded in (\d+) evidence items$/, "基於 $1 項證據資料"],
  [/^Source · (.+)$/, "來源 · $1"],
  [/^(CLINIC ADMIN|NURSE \/ CLINICAL ASSISTANT|DOCTOR|MEASUREMENT) · (.+)$/, (_, role, rest) => `${translatePlain(role)} · ${translatePlain(rest)}`]
];

const originals = new WeakMap();

function isZhActive() {
  const quietButtons = Array.from(document.querySelectorAll(".button--quiet"));
  const hasZhToggleOn = quietButtons.some((button) => button.textContent.trim() === "EN");
  return hasZhToggleOn || Boolean(document.querySelector(".locale-demo"));
}

function preserveSpacing(source, translated) {
  const leading = source.match(/^\\s*/)?.[0] ?? "";
  const trailing = source.match(/\\s*$/)?.[0] ?? "";
  return `${leading}${translated}${trailing}`;
}

function translatePlain(value) {
  const trimmed = value.trim();
  if (!trimmed) return value;
  if (DICT.has(trimmed)) return preserveSpacing(value, DICT.get(trimmed));
  for (const [pattern, replacement] of PATTERNS) {
    const match = trimmed.match(pattern);
    if (!match) continue;
    const translated = typeof replacement === "function"
      ? replacement(...match)
      : trimmed.replace(pattern, replacement);
    return preserveSpacing(value, translated);
  }
  return value;
}

function translateTextNode(node, active) {
  const current = node.nodeValue;
  if (!active) {
    originals.set(node, current);
    return;
  }
  if (!originals.has(node) || current !== translatePlain(originals.get(node))) {
    originals.set(node, current);
  }
  const original = originals.get(node);
  const next = translatePlain(original);
  if (node.nodeValue !== next) node.nodeValue = next;
}

function walk(root, active) {
  if (!root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      if (!node.nodeValue || !node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
      const parent = node.parentElement;
      if (!parent) return NodeFilter.FILTER_REJECT;
      if (["SCRIPT", "STYLE", "NOSCRIPT"].includes(parent.tagName)) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    }
  });
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach((node) => translateTextNode(node, active));
}

let scheduled = false;
function applyZhLocalization() {
  if (scheduled) return;
  scheduled = true;
  requestAnimationFrame(() => {
    scheduled = false;
    walk(document.body, isZhActive());
  });
}

const observer = new MutationObserver(applyZhLocalization);
observer.observe(document.documentElement, { childList: true, subtree: true, characterData: true });
window.addEventListener("DOMContentLoaded", applyZhLocalization);
window.addEventListener("click", () => setTimeout(applyZhLocalization, 0), true);
applyZhLocalization();
